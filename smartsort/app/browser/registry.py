"""Windows registration of the native messaging host.

Only the per-user (``HKCU``) keys owned by SmartSort are created, and
uninstallation removes exactly those keys and the generated manifest file.
No administrator rights are required and no unrelated browser setting is
touched.
"""

from __future__ import annotations

import json
import logging
import os
import sys
from dataclasses import dataclass, field
from pathlib import Path

from ..config.defaults import APP_DESCRIPTION, APP_NAME, NATIVE_HOST_NAME

logger = logging.getLogger(__name__)

# Per-user registry roots for each Chromium-based browser that supports the
# native messaging API with the same manifest format.
BROWSER_REGISTRY_ROOTS: dict[str, str] = {
    "chrome": r"Software\Google\Chrome\NativeMessagingHosts",
    "edge": r"Software\Microsoft\Edge\NativeMessagingHosts",
    "chromium": r"Software\Chromium\NativeMessagingHosts",
    "brave": r"Software\BraveSoftware\Brave-Browser\NativeMessagingHosts",
}

DEFAULT_BROWSERS: tuple[str, ...] = ("chrome", "edge")

LAUNCHER_BAT_NAME = "smartsort-host.cmd"
HOST_EXE_NAME = "smartsort-host.exe"


@dataclass
class InstallResult:
    ok: bool
    manifest_path: Path | None = None
    launcher_path: Path | None = None
    browsers: list[str] = field(default_factory=list)
    errors: list[str] = field(default_factory=list)
    actions: list[str] = field(default_factory=list)


def _winreg():
    if sys.platform != "win32":
        raise OSError("native messaging registration is only supported on Windows")
    import winreg

    return winreg


def build_manifest(launcher_path: Path, extension_ids: list[str]) -> dict:
    origins = [f"chrome-extension://{ext.lower()}/" for ext in extension_ids]
    return {
        "name": NATIVE_HOST_NAME,
        "description": f"{APP_NAME} native messaging host - {APP_DESCRIPTION}",
        "path": str(launcher_path),
        "type": "stdio",
        "allowed_origins": origins,
    }


def resolve_launcher(app_root: Path | None = None) -> Path:
    """Return the executable/cmd file the browser should launch.

    A frozen build ships ``smartsort-host.exe`` next to the GUI executable. In a
    source checkout we generate a small ``.cmd`` wrapper that runs the module
    with the current interpreter.
    """
    exe_dir = Path(sys.executable).parent
    packaged = exe_dir / HOST_EXE_NAME
    if packaged.exists():
        return packaged
    if getattr(sys, "frozen", False):
        return packaged  # expected to exist after a build; reported as missing

    root = app_root or Path(__file__).resolve().parents[3]
    wrapper = root / "scripts" / LAUNCHER_BAT_NAME
    return wrapper


def write_launcher(app_root: Path, target: Path) -> Path:
    """Create the developer-mode ``.cmd`` launcher used by the manifest."""
    python = Path(sys.executable)
    lines = [
        "@echo off",
        "rem Generated by SmartSort. Runs the native messaging host.",
        f'cd /d "{app_root}"',
        f'set "PYTHONPATH={app_root}"',
        f'"{python}" -m smartsort.app.browser.native_host %*',
    ]
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text("\r\n".join(lines) + "\r\n", encoding="utf-8")
    return target


def install(
    *,
    extension_ids: list[str],
    manifest_path: Path,
    browsers: tuple[str, ...] = DEFAULT_BROWSERS,
    app_root: Path | None = None,
) -> InstallResult:
    if not extension_ids:
        return InstallResult(
            ok=False,
            errors=[
                "no_extension_ids: load the extension in Chrome/Edge first and copy its ID"
            ],
        )

    launcher = resolve_launcher(app_root)
    if not launcher.exists() and not getattr(sys, "frozen", False):
        root = app_root or Path(__file__).resolve().parents[3]
        launcher = write_launcher(root, manifest_path.parent / LAUNCHER_BAT_NAME)
    if not launcher.exists():
        return InstallResult(
            ok=False,
            errors=[f"launcher_missing: {launcher}"],
        )

    manifest = build_manifest(launcher, extension_ids)
    try:
        manifest_path.parent.mkdir(parents=True, exist_ok=True)
        manifest_path.write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    except OSError as exc:
        return InstallResult(ok=False, errors=[f"manifest_write_failed: {exc}"])

    result = InstallResult(ok=True, manifest_path=manifest_path, launcher_path=launcher)
    try:
        winreg = _winreg()
    except OSError as exc:
        result.ok = False
        result.errors.append(str(exc))
        return result

    for browser in browsers:
        root = BROWSER_REGISTRY_ROOTS.get(browser)
        if root is None:
            result.errors.append(f"unsupported_browser: {browser}")
            continue
        key_path = f"{root}\\{NATIVE_HOST_NAME}"
        try:
            with winreg.CreateKeyEx(
                winreg.HKEY_CURRENT_USER, key_path, 0, winreg.KEY_WRITE
            ) as key:
                winreg.SetValueEx(key, "", 0, winreg.REG_SZ, str(manifest_path))
            result.browsers.append(browser)
            result.actions.append(f"registered {browser}: HKCU\\{key_path}")
        except OSError as exc:
            result.ok = False
            result.errors.append(f"{browser}: {exc}")

    if not result.browsers:
        result.ok = False
    return result


def uninstall(
    *,
    manifest_path: Path,
    browsers: tuple[str, ...] = tuple(BROWSER_REGISTRY_ROOTS),
) -> InstallResult:
    result = InstallResult(ok=True, manifest_path=manifest_path)
    try:
        winreg = _winreg()
    except OSError as exc:
        result.ok = False
        result.errors.append(str(exc))
        return result

    for browser in browsers:
        root = BROWSER_REGISTRY_ROOTS.get(browser)
        if root is None:
            continue
        key_path = f"{root}\\{NATIVE_HOST_NAME}"
        try:
            winreg.DeleteKey(winreg.HKEY_CURRENT_USER, key_path)
            result.actions.append(f"removed HKCU\\{key_path}")
        except FileNotFoundError:
            pass
        except OSError as exc:
            result.errors.append(f"{browser}: {exc}")
            result.ok = False

    for path in (manifest_path, manifest_path.parent / LAUNCHER_BAT_NAME):
        try:
            if path.exists():
                path.unlink()
                result.actions.append(f"deleted {path}")
        except OSError as exc:
            result.errors.append(f"delete_failed {path}: {exc}")
            result.ok = False
    return result


def status(browsers: tuple[str, ...] = tuple(BROWSER_REGISTRY_ROOTS)) -> dict[str, str | None]:
    """Return the registered manifest path per browser (``None`` when absent)."""
    try:
        winreg = _winreg()
    except OSError:
        return {browser: None for browser in browsers}
    result: dict[str, str | None] = {}
    for browser in browsers:
        root = BROWSER_REGISTRY_ROOTS.get(browser)
        if root is None:
            result[browser] = None
            continue
        key_path = f"{root}\\{NATIVE_HOST_NAME}"
        try:
            with winreg.OpenKey(winreg.HKEY_CURRENT_USER, key_path, 0, winreg.KEY_READ) as key:
                value, _kind = winreg.QueryValueEx(key, "")
                result[browser] = str(value)
        except OSError:
            result[browser] = None
    return result


def open_extension_folder() -> Path | None:
    """Locate the bundled extension directory for the 'load unpacked' flow."""
    candidates: list[Path] = []
    if getattr(sys, "frozen", False):
        exe_dir = Path(sys.executable).parent
        # A build script may place a copy next to the executable for
        # discoverability; otherwise PyInstaller's data folder holds it.
        candidates.append(exe_dir / "browser_extension")
        bundle = getattr(sys, "_MEIPASS", None)
        if bundle:
            candidates.append(Path(bundle) / "browser_extension")
    candidates.append(Path(__file__).resolve().parents[3] / "browser_extension")
    for candidate in candidates:
        if candidate.is_dir():
            return candidate
    return None


def reveal_in_explorer(path: Path) -> None:
    try:
        os.startfile(str(path))  # type: ignore[attr-defined]
    except (AttributeError, OSError):  # pragma: no cover
        logger.warning("cannot open %s", path, exc_info=True)
