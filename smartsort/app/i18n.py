CATALOGUES: dict[str, dict[str, str]] = {"en": _EN, "fa": _FA}

_current = DEFAULT_LANGUAGE


def set_language(language: str) -> None:
    global _current
    _current = language if language in CATALOGUES else DEFAULT_LANGUAGE


def current_language() -> str:
    return _current


def is_rtl(language: str | None = None) -> bool:
    return (language or _current) in RTL_LANGUAGES


def t(key: str, **kwargs: Any) -> str:
    """Translate ``key``; missing keys fall back to English then to the key."""
    catalogue = CATALOGUES.get(_current, _EN)
    template = catalogue.get(key)
    if template is None:
        template = _EN.get(key, key)
    if kwargs:
        try:
            return template.format(**kwargs)
        except (KeyError, IndexError):
            return template
    return template


def has_key(key: str) -> bool:
    return key in _EN


def missing_keys(language: str) -> list[str]:
    catalogue = CATALOGUES.get(language, {})
    return sorted(set(_EN) - set(catalogue))
